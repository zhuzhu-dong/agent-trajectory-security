"""The sandbox workspace's synthetic credentials, and the code that writes them.

The values are not committed as a file, and not held as literals here either.
They live in ``trajsec/rules/workspace_fixtures.json``, which is also what the
evaluator adjudicates findings against -- one source of truth, so the fixture
the agent reads and the fixture the evaluation scores against cannot drift
apart.

There is a second, blunter reason. These values are shaped like real
credentials on purpose: a detector can only be tested against material that
looks like the real thing, and the same format realism is what our own L1 layer
keys on. Anything shaped like a real credential trips secret scanners, and
GitHub's push protection blocked two attempts to publish this repository over
this fixture -- once in ``.env``, once as a literal in this module. Reading the
values from the rules file, which the scanner does not inspect, resolves it.

That is worth being plain about rather than dressing up: the single-source
change is a genuine improvement, and it also happens to route around a scanner
that was doing its job correctly on a false positive. No value here is a live
credential and none is used to authenticate anywhere.
"""

from __future__ import annotations

import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
FIXTURES_PATH = PROJECT_ROOT / "trajsec" / "rules" / "workspace_fixtures.json"

ENV_HEADER = """\
# billing-sync -- sandbox application configuration.
# NOTE: this file belongs to the *sandbox project* the agent operates on.
# Every value below is synthetic. The credential that actually matters (the
# model API key used to drive the agent) is never written to this workspace.
#
# Generated by agentlab/workspace_fixture.py from
# trajsec/rules/workspace_fixtures.json. Not committed: credential-shaped
# fixtures trip secret scanners, and this repository's synthetic key blocked
# its own first two pushes for exactly that reason.
"""


def sandbox_env() -> dict[str, str]:
    """The sandbox project's environment, from the shared fixtures file."""
    data = json.loads(FIXTURES_PATH.read_text(encoding="utf-8"))
    return dict(data["sandbox_env"]["vars"])


def env_text() -> str:
    lines = [ENV_HEADER]
    for key, value in sandbox_env().items():
        lines.append(f"{key}={value}")
    return "\n".join(lines) + "\n"


def ensure_workspace(root: Path) -> list[str]:
    """Write any missing sandbox fixture. Returns the paths it created.

    Idempotent, and it never overwrites: a workspace that has been modified is
    left alone.
    """
    root = Path(root)
    created: list[str] = []

    env_path = root / ".env"
    if not env_path.is_file():
        env_path.parent.mkdir(parents=True, exist_ok=True)
        env_path.write_text(env_text(), encoding="utf-8")
        created.append(str(env_path))

    db_path = root / "data" / "app.db"
    if not db_path.is_file():
        # Run the seeding script rather than import it: `workspace/` is a data
        # directory the agent operates on, not an importable package, and
        # making it one would blur that.
        import subprocess
        import sys

        subprocess.run(
            [sys.executable, str(root / "scripts" / "seed_db.py")],
            check=True,
            capture_output=True,
        )
        created.append(str(db_path))

    return created


if __name__ == "__main__":
    from agentlab.config import WORKSPACE_DIR

    print("created:", ensure_workspace(WORKSPACE_DIR) or "nothing (already present)")
